let fitT = null;
/* ONE SCREEN FOR ALL OF THEM, the way the Case Management course's slides fit (fitSlideZoom / paginateLessonSlide
   in its js/cm-updates.js). The slide's frame takes the room left on the screen; its header, ribbon and bar keep
   their size, and only what is on its card (the sheet, or the day card on navy) is scaled down until the whole
   slide fits, to 80% at the smallest (smaller text read as a different, harder slide). Only a slide that would have to shrink further is read in pages: its
   blocks are dealt into screenfuls, Previous / Next turn the pages before moving to the next slide, and the bar
   says which page it is. Nothing scrolls.
   Split screen keeps the whole slide in its column instead: there the point is reading two slides side by side. */
const FIT_MIN = 0.8;
// a reading (Day 1's Personal Injury parts) is never scaled down: it is dealt into pages at full size, read with Next
// (and a slide the build marks read: Day 11's LOR Drafting guidelines)
const isReadPart = s => !!s && (!!s.read || Object.values(KC_NEXT[DD.day] || {}).some(k => k.parts.test(s.id)));
const PAGE_ZOOM = 0.85;   // a page holds a little more than the screen, scaled down to fit (to 85%: the text stays readable)
// a slide with room to spare is drawn bigger, up to max, so its content fills the sheet instead of sitting small in it
function zoomUp(box, max){
  const inner = [...box.children].filter(k => k.style.display !== "none");
  if(!inner.length || !box.clientHeight || box.scrollHeight > box.clientHeight + 2) return;
  let z = parseFloat(inner[0].style.zoom) || 1; if(z < 1) return;
  while(z < max){
    const up = Math.round((z + 0.05) * 100) / 100; inner.forEach(k => { k.style.zoom = String(up); });
    if(box.scrollHeight > box.clientHeight + 2){ inner.forEach(k => { k.style.zoom = z === 1 ? "" : String(z); }); break; }
    z = up;
  }
}
// scales the card's content down until it fits; true when it does
function zoomToFit(box, min){
  const inner = [...box.children];
  inner.forEach(k => { k.style.zoom = ""; });
  box.style.zoom = ""; box.scrollTop = 0;
  let z = 1;
  while(box.clientHeight && box.scrollHeight > box.clientHeight + 2 && z > min){
    z = Math.round((z - 0.05) * 100) / 100; inner.forEach(k => { k.style.zoom = String(z); });
  }
  return box.scrollHeight <= box.clientHeight + 2;
}
function sheetPages(sheet){
  const kids = [...sheet.children];
  kids.forEach(k => { k.style.display = ""; k.classList.remove("ftdd-pi-compact"); });
  // (a block dealt out by its own rows had them hidden page by page: they are shown again before the slide is dealt anew)
  sheet.querySelectorAll("[data-ftdd-paged]").forEach(k => { k.style.display = ""; k.removeAttribute("data-ftdd-paged"); });
  sheet.style.zoom = "";
  // the trainer's own slide is an editor, not a page to turn: paging it would hide half the form
  if(DD.split || kids.length < 2 || sheet.classList.contains("ftdd-sheet-edit")) return [kids];
  const room = sheet.clientHeight, read = sheet.matches(".ftdd-read, .ftdd-sa");   // (Day 1's Installation of SA reads like the reading: one size, page by page)
  // a reading's text-and-chart row is never taller than the page, even drawn up to 1.15: its chart gives way, so its text
  // isn't shrunk to fit a tall chart
  if(read && room) sheet.style.setProperty("--ftdd-pi-h", Math.floor(room / 1.15 - 8) + "px");
  if(!room || (read ? sheet.scrollHeight - room <= 2 : zoomToFit(sheet, FIT_MIN))) return [kids];
  kids.forEach(k => { k.style.zoom = ""; });   // too long even at half size: dealt into pages at full size
  const hOf = x => { const st = getComputedStyle(x); return x.offsetHeight + (parseFloat(st.marginTop) || 0) + (parseFloat(st.marginBottom) || 0); };
  // a block taller than the screen on its own (a long list, a table) is dealt out by its own rows
  const units = [];
  kids.forEach(k => {
    const inner = [...k.children];
    // (a reading's text-and-chart row stays whole: it is one page's worth, scaled a little if it must)
    // (and an embedded video or sheet stays with its name: ftdd-inline)
    if(hOf(k) > room && inner.length > 1 && !k.classList.contains("ftdd-pi-row") && !k.classList.contains("ftdd-inline") && !k.classList.contains("ftdd-card4")) units.push(...inner); else units.push(k);
  });
  // a page that would be less than about a third full (a section's last paragraph on its own) joins the page before it,
  // which fitSheets scales a little to hold it, rather than a near-empty page
  const capAll = room / (read ? 1 : PAGE_ZOOM), sumH = p => p.reduce((a, x) => a + hOf(x), 0);
  // and a first page that is only a heading and its introduction (the reading's "Time Limits …" over the statute of
  // limitations sections) goes on top of the page after it, so the heading opens the page its sections are on
  // (on the reading too: a section's last paragraph stays with its section, the page scaled a little to hold it)
  const fold = ps => { const out = ps.reduce((out, p) => { const prev = out[out.length - 1];
    if(prev && sumH(p) < capAll * (read ? 0.55 : 0.3) && sumH(prev) + sumH(p) <= capAll * (read ? 1.12 : 1.35)) out[out.length - 1] = prev.concat(p); else out.push(p); return out; }, []);
    const introOnly = p => p.length <= 3 && /^H[1-6]$/.test(p[0].tagName) && sumH(p) < capAll * 0.5;
    if(out.length > 1 && introOnly(out[0]) && sumH(out[0]) + sumH(out[1]) <= capAll / (read ? 0.6 : FIT_MIN)) out.splice(0, 2, out[0].concat(out[1]));   // (fitSheets scales it to fit)
    // the reading: a short page that is only the end of a section (the text under a text-and-chart row) goes on top of
    // the next page, whose row is then drawn compact (only as tall as its text) to make room, so it never stands alone
    // (scaled only a little to fit, 0.9 at most: the reading stays big, a page more rather than smaller text)
    if(read) for(let i = 0; i < out.length - 1; i++){
      const p = out[i], nx = out[i + 1], row = nx[0];
      // (a page that opens with a heading, a section's introduction, keeps its own page at full size)
      if(sumH(p) >= capAll * 0.5 || /^H[1-6]$/.test(p[0].tagName) || !row.classList.contains("ftdd-pi-row") || p.some(x => x.classList.contains("ftdd-pi-row"))) continue;
      row.classList.add("ftdd-pi-compact");
      if(sumH(p) + sumH(nx) <= capAll / 0.9){ out.splice(i, 2, p.concat(nx)); } else row.classList.remove("ftdd-pi-compact");
    }
    return out; };
  const pages = []; let page = [], used = 0;
  // a page holds what fits on the screen at three quarters size: a block that would hang off the foot of that starts
  // the next page, and fitSheets scales the page down to fit
  units.forEach(k => {
    const h = hOf(k);
    if(page.length && used + h > room / (read ? 1 : PAGE_ZOOM)){
      // a heading never ends a page: it moves to the next one with the text it heads
      const carry = [];
      while(page.length > 1 && /^H[1-6]$/.test(page[page.length - 1].tagName)) carry.unshift(page.pop());
      pages.push(page); page = carry; used = carry.reduce((a, x) => a + hOf(x), 0);
    }
    page.push(k); used += h;
  });
  if(page.length) pages.push(page);
  // the same number of pages, filled about evenly, so the last page isn't a line or two on its own: the smallest page
  // height that still deals the slide into that many pages (a heading still never ends a page)
  if(pages.length > 1){
    const total = units.reduce((a, x) => a + hOf(x), 0), cap = room / (read ? 1 : PAGE_ZOOM), tallest = Math.max(...units.map(hOf));
    const deal = limit => { const out = []; let pg = [], u = 0;
      units.forEach(k => { const h = hOf(k);
        if(pg.length && u + h > limit){ const carry = []; while(pg.length > 1 && /^H[1-6]$/.test(pg[pg.length - 1].tagName)) carry.unshift(pg.pop());
          out.push(pg); pg = carry; u = carry.reduce((a, x) => a + hOf(x), 0); }
        pg.push(k); u += h; });
      if(pg.length) out.push(pg); return out; };
    for(let limit = Math.max(total / pages.length, tallest); limit < cap; limit += Math.max(8, cap / 60)){
      const even = deal(limit); if(even.length <= pages.length) return fold(even);
    }
  }
  return pages.length ? fold(pages) : [kids];
}
