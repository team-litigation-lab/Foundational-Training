#!/usr/bin/env node
/* Writes js/ft-cases-data.js: the facts of the training CMS's Training Library cases (MC-01 …), for the Practice
   Sessions' assigned cases and their automated checks (js/ft-sessions.js).
   Usage:  node build/make_cases.cjs <path to the CaseManagementTraining repo's mock-cases.js>
   The cases live in the CMS (CaseManagementTraining/mock-cases.js); this copies only what the sessions check:
   the client and DOB, the case's phase and attorney, the insurance claims, the treating providers and liens.
   Run it again when the Training Library changes. */
const fs = require("fs"), path = require("path");
const src = process.argv[2];
if (!src) { console.error("usage: node build/make_cases.cjs <path to mock-cases.js>"); process.exit(1); }
const { MOCK_CASES, MOCK_FIRM } = require(path.resolve(src));
const pick = (o, keys) => Object.fromEntries(keys.filter((k) => o && o[k] != null && o[k] !== "").map((k) => [k, o[k]]));
const cases = MOCK_CASES.map((c) => {
  const docs = (c.docs || []).map((d) => String(d.summary || "")).join(" ");
  const em = (c.client && c.client.emergency) || {};
  return {
    id: c.id, no: c.caseNumber, level: c.level, summary: c.summary, type: c.caseType, phase: c.phase,
    attorney: c.attorney, cm: c.caseManager, dol: c.dateOfLoss, sol: c.sol,
    client: pick(c.client || {}, ["name", "dob", "phone", "email", "address"]),
    authorized: /power of attorney|poa|guardian/i.test(String(em.relationship || "")) ? `${em.name} (${em.relationship})` : "",
    hipaa: /HIPAA/i.test(docs) ? (/not yet signed|unsigned|pending/i.test(docs) ? "sent, not signed" : "signed") : "",
    bi: (c.bi || []).map((b) => pick(b, ["holder", "carrier", "policy", "claim", "adjuster", "contact", "liability", "limits"])),
    pipum: (c.pipum || []).map((b) => pick(b, ["type", "holder", "carrier", "policy", "claim", "adjuster", "contact", "limits"])),
    health: pick(c.health || {}, ["carrier", "memberId", "group"]),
    providers: (c.facilities || []).map((f) => Object.assign(pick(f, ["name", "phone", "email", "dates", "status", "charges"]),
      { specialty: f.specialty === "Other" ? (f.specialtyOther || "Other") : f.specialty })),
    liens: (c.liens || []).map((l) => pick(l, ["type", "entity", "amount", "status"]))
  };
});
const firm = pick(MOCK_FIRM, ["name", "mainLine", "fax", "hours", "address"]);
firm.directory = MOCK_FIRM.directory || []; firm.rules = MOCK_FIRM.rules || []; firm.sop = MOCK_FIRM.sop || [];
const out = `/* Generated by build/make_cases.cjs from the training CMS's Training Library (CaseManagementTraining/mock-cases.js).
   Don't edit by hand: run  node build/make_cases.cjs <path to mock-cases.js>  again. Every person, number and case here is fictional. */
window.FT_CMS_FIRM = ${JSON.stringify(firm)};
window.FT_CASES = ${JSON.stringify(cases).replace(/\},\{"id"/g, '},\n{"id"')};
`;
fs.writeFileSync(path.join(__dirname, "..", "js", "ft-cases-data.js"), out);
console.log(`js/ft-cases-data.js: ${cases.length} cases`);
