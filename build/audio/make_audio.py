#!/usr/bin/env python3
"""Renders the sample intake calls and Atty. Magdalena's PI consultation (build/audio/intake_samples.json) to MP3,
and writes js/ft-intake-samples.js (the transcripts, each line's start time, and the sample minutes).

  pip install piper-tts
  python3 build/audio/make_audio.py <folder with the Piper voices: amy.onnx, ryan.onnx, kristin.onnx, …>

Voices (rhasspy/piper-voices v1.0.0, en_US, medium): amy, ryan, kristin, hfc_male (hfcm), hfc_female (hfcf),
lessac, john. Each line is spoken by its speaker's voice, with a short pause between lines; the calls go through a
telephone band-pass so they sound like the phone recordings they sit beside. Needs ffmpeg."""
import json, os, subprocess, sys, tempfile, wave

R = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(R, "build/audio/intake_samples.json")
OUT = os.path.join(R, "ft/day7/audio")
JS = os.path.join(R, "js/ft-intake-samples.js")
VOICES = sys.argv[1] if len(sys.argv) > 1 else "voices"
RATE = 22050
SAME, TURN = 0.35, 0.6   # seconds of silence after a line: same speaker next, or the other speaker

def say(voice, text, path):
    subprocess.run([sys.executable, "-m", "piper", "-m", os.path.join(VOICES, voice + ".onnx"), "-f", path],
                   input=text.encode(), check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)

def render(item, phone):
    lines, times, frames = item["lines"], [], []
    with tempfile.TemporaryDirectory() as tmp:
        t = 0.0
        for i, (who, text) in enumerate(lines):
            p = os.path.join(tmp, f"{i}.wav"); say(item["voices"][who], text, p)
            with wave.open(p) as w:
                assert w.getframerate() == RATE and w.getnchannels() == 1
                data = w.readframes(w.getnframes())
            times.append(round(t, 1)); frames.append(data); t += len(data) / 2 / RATE
            gap = SAME if i + 1 < len(lines) and lines[i + 1][0] == who else TURN
            frames.append(b"\0\0" * int(gap * RATE)); t += gap
        raw = os.path.join(tmp, "all.wav")
        with wave.open(raw, "wb") as w:
            w.setnchannels(1); w.setsampwidth(2); w.setframerate(RATE); w.writeframes(b"".join(frames))
        mp3 = os.path.join(OUT, item["id"] + ".mp3")
        af = ["-af", "highpass=f=300,lowpass=f=3400,volume=1.4"] if phone else []
        subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", raw, *af, "-ac", "1", "-b:a", "48k", mp3], check=True)
    return times, round(t, 1)

def main():
    d = json.load(open(SRC)); os.makedirs(OUT, exist_ok=True)
    out = {"firm": d["firm"], "calls": [], "consult": None}
    for c in d["calls"]:
        times, dur = render(c, True)
        out["calls"].append({k: c[k] for k in ("id", "title", "kind", "about", "listen_for")} |
                            {"src": f"/ft/day7/audio/{c['id']}.mp3", "dur": dur, "lines": [[w, x, s] for (w, x), s in zip(c["lines"], times)]})
        print(f"{c['id']}: {dur:.0f}s, {len(c['lines'])} lines")
    k = d["consult"]; times, dur = render(k, False)
    m = dict(k["minutes"]); stamp = lambda s: f"[{int(s // 60)}:{int(s % 60):02d}]"
    m["discussion"] = "\n".join(f"{stamp(times[i])} {x}" for i, x in m["discussion"])
    out["consult"] = {"id": k["id"], "title": k["title"], "about": k["about"], "src": f"/ft/day7/audio/{k['id']}.mp3", "dur": dur,
                      "lines": [[w, x, s] for (w, x), s in zip(k["lines"], times)], "minutes": m}
    print(f"{k['id']}: {dur:.0f}s, {len(k['lines'])} lines")
    open(JS, "w").write("// Generated by build/audio/make_audio.py from build/audio/intake_samples.json — edit that file, not this one.\n"
                        "// Fictional people, firm and cases, written for training.\n"
                        "window.FT_INTAKE_SAMPLES = " + json.dumps(out, ensure_ascii=False) + ";\n")

main()
