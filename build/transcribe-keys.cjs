// 🎧 The Transcription Activity's reference: the two interview recordings' transcripts (build/audio/interviews.json, the
// scripts the recordings are made from), written to transcribe-keys.js at the root for worker.js (/api/transcribe/grade), which
// grades Accuracy, Completeness, Speaker Attribution and the Concerns & Advice against them. Never sent to a page:
// .assetsignore keeps transcribe-keys.js out of the site, as it does assess-keys.js. Run again after interviews.json changes
// (.github/scripts/transcribe-grade.cjs fails while the two differ).
// Usage: node build/transcribe-keys.cjs           (writes transcribe-keys.js)
//        node build/transcribe-keys.cjs --check   (changes nothing: exits 1 when transcribe-keys.js isn't up to date)
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..'), OUT = path.join(ROOT, 'transcribe-keys.js');
function build() {
  const d = JSON.parse(fs.readFileSync(path.join(ROOT, 'build/audio/interviews.json'), 'utf8')), keys = {};
  for (const it of d.interviews) { const m = /recording-(\d)$/.exec(it.id); if (m) keys[m[1]] = { title: it.title, lines: it.lines }; }
  return `// 🎧 GENERATED by build/transcribe-keys.cjs from build/audio/interviews.json: do not edit here.\n` +
    `// The Transcription Activity's interview transcripts (A = Atty. Magdalena, C = the client), read by worker.js only\n` +
    `// (/api/transcribe/grade), never sent to a page (.assetsignore keeps this file out of the site).\n` +
    `export const TRANSCRIBE_KEYS = {\n${Object.entries(keys).map(([n, k]) => `  ${n}: { title: ${JSON.stringify(k.title)}, lines: [\n${k.lines.map(l => "    " + JSON.stringify(l)).join(",\n")}\n  ] }`).join(",\n")}\n};\n`;
}
module.exports = { build };
if (require.main === module) {
  const text = build();
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (cur !== text) { console.error('transcribe-keys.js is out of date: run node build/transcribe-keys.cjs'); process.exit(1); }
    console.log('transcribe-keys.js follows build/audio/interviews.json'); process.exit(0);
  }
  fs.writeFileSync(OUT, text); console.log('transcribe-keys.js written from build/audio/interviews.json');
}
